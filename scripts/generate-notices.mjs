#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from the dependency metadata of the Rust and JavaScript
// lockfiles. Run after changing dependencies: `node scripts/generate-notices.mjs`.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const shell = process.platform === "win32";

function cargoPackages() {
  const raw = execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--manifest-path", "src-tauri/Cargo.toml"], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    shell,
  });
  const meta = JSON.parse(raw);
  const resolved = new Set(meta.resolve.nodes.map((n) => n.id));
  return meta.packages
    .filter((p) => resolved.has(p.id) && p.name !== "darkload")
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? p.license_file ?? "See package", url: p.repository ?? "" }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function npmPackages() {
  const raw = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell });
  const byLicense = JSON.parse(raw);
  const rows = [];
  for (const [license, packages] of Object.entries(byLicense)) {
    for (const p of packages) {
      for (const version of p.versions ?? [p.version]) rows.push({ name: p.name, version, license, url: p.homepage ?? "" });
    }
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name));
}

const table = (rows) =>
  ["| Package | Version | License |", "| --- | --- | --- |", ...rows.map((r) => `| ${r.url ? `[${r.name}](${r.url})` : r.name} | ${r.version} | ${r.license} |`)].join("\n");

const cargo = cargoPackages();
const npm = npmPackages();

writeFileSync(
  "THIRD_PARTY_NOTICES.md",
  `# Third-party notices

DarkLoad's original source code is licensed under the MIT License (see \`LICENSE\`). DarkLoad is built on the open-source projects listed below, which remain under their own licenses. License texts are included with each package's source distribution.

This file is generated by \`scripts/generate-notices.mjs\` from the project's lockfiles.

## Components downloaded at runtime

These tools are **not** bundled in DarkLoad's installers. DarkLoad downloads them on request from their official releases and verifies their published SHA-256 checksums.

| Component | Source | License |
| --- | --- | --- |
| yt-dlp | https://github.com/yt-dlp/yt-dlp | The Unlicense (standalone builds include third-party libraries under their own licenses) |
| FFmpeg and FFprobe | https://github.com/yt-dlp/FFmpeg-Builds | GPL-3.0-or-later (GPL builds); source code: https://ffmpeg.org |
| Deno | https://github.com/denoland/deno | MIT |

## Fonts and icons

| Asset | License |
| --- | --- |
| Inter (via @fontsource-variable/inter) | SIL Open Font License 1.1 |
| Lucide icons | ISC |

## Rust crates (${cargo.length})

${table(cargo)}

## JavaScript packages shipped in the interface (${npm.length})

${table(npm)}
`,
);
console.log(`THIRD_PARTY_NOTICES.md written (${cargo.length} crates, ${npm.length} npm packages).`);
